//! The clock as php-src reads it.

/// `time(NULL)`: the current Unix time in whole seconds (0 before the
/// epoch).
#[must_use]
pub fn now() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| i64::try_from(d.as_secs()).unwrap_or(i64::MAX))
}
